import { useEffect, useState } from 'react'
import { api } from '../lib/api'
import { PageHeader, ErrorBox } from '../components/UI'

export default function Datasets() {
  const [datasets, setDatasets] = useState([])
  const [preview,  setPreview]  = useState(null)
  const [loading,  setLoading]  = useState(true)
  const [busy,     setBusy]     = useState(false)
  const [error,    setError]    = useState('')

  const load = () => {
    setLoading(true)
    api.datasets.list()
      .then(d => setDatasets(d.datasets || []))
      .catch(e => setError(e.message))
      .finally(() => setLoading(false))
  }

  useEffect(load, [])

  const handleSynthetic = async () => {
    setBusy(true); setError('')
    try {
      const seed = Math.floor(Math.random() * 99999)
      const res = await api.datasets.generate({ n_rows: 600, n_features: 5, seed })
      setPreview({ filename: res.dataset.filename, cols: res.cols, rows: res.preview, labelCol: res.label_col })
      load()
    } catch (e) { setError(e.message) }
    finally { setBusy(false) }
  }

  const handleUpload = async file => {
    if (!file) return
    setBusy(true); setError('')
    try {
      const res = await api.datasets.upload(file)
      setPreview({ filename: res.dataset.filename, cols: res.cols, rows: res.preview, labelCol: res.label_col })
      load()
    } catch (e) { setError(e.message) }
    finally { setBusy(false) }
  }

  const handleDelete = async id => {
    if (!confirm('Delete this dataset?')) return
    await api.datasets.delete(id).catch(e => setError(e.message))
    load()
  }

  return (
    <div className="space-y-8">
      <PageHeader title="Datasets" sub="Upload a labeled CSV or generate a synthetic binary-classification dataset." />

      <div className="grid md:grid-cols-2 gap-4">
        <div className="panel p-6">
          <div className="label mb-2">Upload CSV</div>
          <p className="text-sm text-mist-500 mb-4">Stored in Supabase Storage · processed by FastAPI · metadata saved to PostgreSQL.</p>
          <label className="btn-ghost cursor-pointer inline-flex">
            {busy ? 'Uploading…' : 'Choose CSV file'}
            <input type="file" accept=".csv" className="hidden" disabled={busy}
              onChange={e => handleUpload(e.target.files[0])} />
          </label>
        </div>
        <div className="panel p-6">
          <div className="label mb-2">Synthetic demo dataset</div>
          <p className="text-sm text-mist-500 mb-4">600 rows · 5 features · balanced binary label. Generated by Python on the FastAPI server.</p>
          <button className="btn-primary" disabled={busy} onClick={handleSynthetic}>
            {busy ? 'Generating…' : 'Generate dataset'}
          </button>
        </div>
      </div>

      <ErrorBox message={error} />

      {preview && (
        <div className="panel p-6">
          <div className="flex items-center justify-between mb-3">
            <h3 className="font-semibold text-sm">Preview — {preview.filename}</h3>
            <span className="text-xs text-mist-500 font-mono">{preview.rows.length} preview rows · label: {preview.labelCol}</span>
          </div>
          <div className="overflow-x-auto scrollbar-thin">
            <table className="data-table">
              <thead><tr>{preview.cols.map(c => <th key={c}>{c}</th>)}</tr></thead>
              <tbody>
                {preview.rows.map((r, i) => (
                  <tr key={i}>{preview.cols.map(c => <td key={c} className="font-mono text-xs">{String(r[c])}</td>)}</tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      <div className="panel p-6">
        <h2 className="text-base font-semibold mb-4">Your datasets</h2>
        {loading ? (
          <div className="text-sm text-mist-500">Loading…</div>
        ) : datasets.length === 0 ? (
          <div className="text-sm text-mist-500 text-center py-8">No datasets yet. Generate or upload one above.</div>
        ) : (
          <table className="data-table">
            <thead><tr><th>Filename</th><th>Rows</th><th>Label col</th><th>Type</th><th>Created</th><th></th></tr></thead>
            <tbody>
              {datasets.map(d => (
                <tr key={d.id}>
                  <td className="font-mono text-xs">{d.filename}</td>
                  <td>{d.rows_count}</td>
                  <td className="font-mono text-signal-400">{d.label_col}</td>
                  <td><span className="badge border-mist-700 text-mist-500">{d.is_synthetic ? 'synthetic' : 'uploaded'}</span></td>
                  <td className="text-mist-500 text-xs">{new Date(d.created_at).toLocaleDateString()}</td>
                  <td><button onClick={() => handleDelete(d.id)} className="text-xs text-rose-400 hover:text-rose-300">delete</button></td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </div>
    </div>
  )
}
